// --- COORDINATOR ---
public sealed class DocumentEnrichmentChallenge : IDocumentEnrichmentChallenge
{
    private static readonly Dictionary<string, Func<IAccountingDocumentComponent, string, IAccountingDocumentComponent>> DecoratorFactories =
        new(StringComparer.OrdinalIgnoreCase)
        {
            ["metadatos"] = (inner, key) => new MetadataDecorator(inner, key),
            ["metadata"] = (inner, key) => new MetadataDecorator(inner, key),
            ["header"] = (inner, key) => new HeaderDecorator(inner, key),
            ["encabezado"] = (inner, key) => new HeaderDecorator(inner, key),
            ["footer"] = (inner, key) => new FooterDecorator(inner, key),
            ["pie"] = (inner, key) => new FooterDecorator(inner, key),
            ["watermark"] = (inner, key) => new WatermarkDecorator(inner, key),
            ["marca_agua"] = (inner, key) => new WatermarkDecorator(inner, key),
            ["signature"] = (inner, key) => new DigitalSignatureDecorator(inner, key),
            ["firma"] = (inner, key) => new DigitalSignatureDecorator(inner, key),
            ["audit"] = (inner, key) => new AuditStampDecorator(inner, key),
            ["auditoria"] = (inner, key) => new AuditStampDecorator(inner, key)
        };

    public ExportedAccountingDocument Export(DocumentExportRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);

        IAccountingDocumentComponent document = new PlainAccountingDocument(request.Body, request.Metadata);

        if (request.Features is null || request.Features.Count == 0)
        {
            return document.Render();
        }

        foreach (var rawFeature in request.Features)
        {
            if (string.IsNullOrWhiteSpace(rawFeature))
            {
                throw new ArgumentException("Export feature cannot be null or whitespace.", nameof(request));
            }

            var featureKey = rawFeature.Trim();
            if (!DecoratorFactories.TryGetValue(featureKey, out var wrap))
            {
                throw new ArgumentException($"Unknown export feature '{rawFeature}'.", nameof(request));
            }

            document = wrap(document, featureKey);
        }

        return document.Render();
    }
}