using AccountingLab.Domain.Education;

namespace AccountingLab.Application.Challenges.DP09Decorator;

public sealed record DocumentExportRequest(string Body, IReadOnlyList<string> Features, IReadOnlyDictionary<string, string> Metadata);
public sealed record ExportedAccountingDocument(string Content, IReadOnlyList<string> AppliedFeatures, IReadOnlyDictionary<string, string> Metadata);
public interface IDocumentEnrichmentChallenge { ExportedAccountingDocument Export(DocumentExportRequest request); }

// --- COMPONENT ---
public interface IAccountingDocumentComponent
{
    ExportedAccountingDocument Render();
}

public sealed class PlainAccountingDocument : IAccountingDocumentComponent
{
    private readonly string _body;
    private readonly IReadOnlyDictionary<string, string> _metadata;

    public PlainAccountingDocument(string body, IReadOnlyDictionary<string, string>? metadata)
    {
        _body = body ?? string.Empty;
        _metadata = metadata is null
            ? new Dictionary<string, string>()
            : new Dictionary<string, string>(metadata);
    }

    public ExportedAccountingDocument Render()
    {
        return new ExportedAccountingDocument(
            Content: _body,
            AppliedFeatures: Array.Empty<string>(),
            Metadata: new Dictionary<string, string>(_metadata));
    }
}

// --- BASE DECORATOR ---
public abstract class AccountingDocumentDecorator : IAccountingDocumentComponent
{
    protected readonly IAccountingDocumentComponent Inner;

    protected AccountingDocumentDecorator(IAccountingDocumentComponent inner)
    {
        Inner = inner ?? throw new ArgumentNullException(nameof(inner));
    }

    public abstract ExportedAccountingDocument Render();

    protected static ExportedAccountingDocument AppendFeature(
        ExportedAccountingDocument current,
        string featureName,
        string updatedContent,
        Action<Dictionary<string, string>>? enrichMetadata = null)
    {
        var applied = new List<string>(current.AppliedFeatures) { featureName };
        var metadata = new Dictionary<string, string>(current.Metadata);
        enrichMetadata?.Invoke(metadata);

        return new ExportedAccountingDocument(
            Content: updatedContent,
            AppliedFeatures: applied.AsReadOnly(),
            Metadata: metadata);
    }
}

// --- CONCRETE DECORATORS ---
public sealed class MetadataDecorator : AccountingDocumentDecorator
{
    private readonly string _featureKey;

    public MetadataDecorator(IAccountingDocumentComponent inner, string featureKey) : base(inner)
    {
        _featureKey = featureKey;
    }

    public override ExportedAccountingDocument Render()
    {
        var current = Inner.Render();
        var metaSummary = current.Metadata.Count == 0
            ? "none"
            : string.Join(", ", current.Metadata.Select(kvp => $"{kvp.Key}={kvp.Value}"));

        var updated = $"{current.Content}\n[METADATA] {metaSummary}";
        return AppendFeature(current, _featureKey, updated, meta => meta["IncludesMetadata"] = "true");
    }
}

public sealed class HeaderDecorator : AccountingDocumentDecorator
{
    private readonly string _featureKey;

    public HeaderDecorator(IAccountingDocumentComponent inner, string featureKey) : base(inner)
    {
        _featureKey = featureKey;
    }

    public override ExportedAccountingDocument Render()
    {
        var current = Inner.Render();
        var title = current.Metadata.TryGetValue("Title", out var t) && !string.IsNullOrWhiteSpace(t)
            ? t
            : current.Metadata.TryGetValue("Company", out var c) && !string.IsNullOrWhiteSpace(c)
                ? c
                : "ACCOUNTING DOCUMENT";

        var updated = $"[HEADER] {title}\n{current.Content}";
        return AppendFeature(current, _featureKey, updated, meta => meta["HasHeader"] = "true");
    }
}

